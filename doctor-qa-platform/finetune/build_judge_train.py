def main():
    old = []
    with open(SRC, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                old.append(json.loads(line))

    # 防重叠检查：新增判定样本的声称不得与评测集 v2 相同
    judge_v2 = []
    v2_path = os.path.join(HERE, "rag_train_judge_v2.jsonl")
    if os.path.exists(v2_path):
        with open(v2_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    judge_v2.append(json.loads(line))
    v2_claims = {s["input"].split("\n\n", 1)[1] for s in judge_v2}
    dup = [s["input"].split("\n\n", 1)[1][:30] for s in NEW if s["input"].split("\n\n", 1)[1] in v2_claims]
    if dup:
        print(f"[警告] 与评测集重复: {dup}")
    else:
        print("防重叠检查通过：新增 30 条与评测集 v2 无重复")

    all_samples = old + NEW
    with open(DST, "w", encoding="utf-8") as f:
        for s in all_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    n_pos = sum(1 for s in NEW if s["output"].startswith("判定：正确"))
    n_neg = len(NEW) - n_pos
    report = [
        f"输入: {SRC}",
        f"输出: {DST}",
        f"问答样本: {len(old)} 条",
        f"新增判定样本: {len(NEW)} 条（正 {n_pos} / 负 {n_neg}）",
        f"合计: {len(all_samples)} 条",
        "防重叠检查: 通过（与评测集 v2 无重复）",
    ]
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(report))
    print("\n".join(report))


if __name__ == "__main__":
    main()
