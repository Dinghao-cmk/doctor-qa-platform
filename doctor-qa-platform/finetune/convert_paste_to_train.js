/* ============ 3. 统一输出 ============ */
function main() {
  const negatives = parseNegatives()
  console.log(`负样本（判定不正确）: ${negatives.length} 条`)
  console.log(`正样本（判定正确）: ${POSITIVES.length} 条`)

  const samples = []
  // 负样本：原样保留"说法：不正确"语义
  for (const it of negatives) {
    samples.push({
      instruction: INSTRUCTION_JUDGE,
      input: `请复核以下病历质控缺陷声称是否成立，并给出判定理由：\n\n${it.claim}`,
      output: fmt(it.verdict, it.reason),
    })
  }
  // 正样本：判定"正确"
  for (const [claim, reason] of POSITIVES) {
    samples.push({
      instruction: INSTRUCTION_JUDGE,
      input: `请复核以下病历质控缺陷声称是否成立，并给出判定理由：\n\n${claim}`,
      output: fmt('正确', reason),
    })
  }

  fs.writeFileSync(OUT, samples.map((s) => JSON.stringify(s)).join('\n') + '\n', 'utf8')
  console.log(`已写入 ${OUT}: ${samples.length} 条（负 ${negatives.length} + 正 ${POSITIVES.length}）`)
  // 抽样展示
  console.log('=== 负样本抽样 ===')
  console.log(JSON.stringify(samples[0], null, 2).slice(0, 400))
  console.log('=== 正样本抽样 ===')
  console.log(JSON.stringify(samples[negatives.length], null, 2).slice(0, 400))
}

main()
