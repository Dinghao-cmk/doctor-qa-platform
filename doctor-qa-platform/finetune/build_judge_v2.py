def main():
    old = []
    with open(SRC, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                old.append(json.loads(line))

    all_samples = old + NEW
    with open(DST, "w", encoding="utf-8") as f:
        for s in all_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    def cnt(items):
        pos = sum(1 for s in items if s["output"].startswith("判定：正确"))
        return len(items), pos, len(items) - pos

    t_old, p_old, n_old = cnt(old)
    t_new, p_new, n_new = cnt(NEW)
    t_all, p_all, n_all = cnt(all_samples)
    report = [
        f"输入: {SRC}",
        f"输出: {DST}",
        f"原评测集: {t_old} 条（正 {p_old} / 负 {n_old}）",
        f"新增: {t_new} 条（正 {p_new} / 负 {n_new}）",
        f"合计: {t_all} 条（正 {p_all} / 负 {n_all}）",
        "",
        "新增样本示例：",
    ]
    for s in NEW[:3] + NEW[10:13]:
        claim = s["input"].split("\n\n", 1)[1]
        report.append(f"  [{s['output'].split(chr(10))[0]}] {claim[:50]}...")
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(report))
    print("\n".join(report))


if __name__ == "__main__":
    main()
